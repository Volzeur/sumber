<?php

namespace App\Services;

use App\Models\LoanPost;
use FPDF;

class PdfService
{
    public function generateLoanReceipt(LoanPost $post)
    {
        $post->load('user');

        $pdf = new Fpdf('P', 'mm', 'A4');
        $pdf->AddPage();
        $pdf->SetAutoPageBreak(true, 20);

        // Header
        $pdf->SetFont('Helvetica', 'B', 22);
        $pdf->Cell(0, 15, $this->sanitize('Kamibantu'), 0, 1, 'C');
        $pdf->SetFont('Helvetica', '', 10);
        $pdf->SetTextColor(113, 113, 122); // muted
        $pdf->Cell(0, 6, $this->sanitize('Loan Request Receipt'), 0, 1, 'C');
        $pdf->Ln(5);

        // Divider line
        $pdf->SetDrawColor(228, 228, 231);
        $pdf->Line(20, $pdf->GetY(), 190, $pdf->GetY());
        $pdf->Ln(8);

        // Reset text color
        $pdf->SetTextColor(9, 9, 11);

        // Post details
        $pdf->SetFont('Helvetica', 'B', 14);
        $pdf->Cell(0, 8, $this->sanitize($post->title), 0, 1);
        $pdf->Ln(3);

        $pdf->SetFont('Helvetica', '', 10);

        $details = [
            ['Borrower', $this->sanitize($post->user?->name)],
            ['Email', $this->sanitize($post->user?->email)],
            ['Amount Needed', $this->sanitize((string) $post->formatted_amount)],
            ['Interest Rate', $this->sanitize($post->interest_rate . '%')],
            ['Total Repayable', $this->sanitize((string) $post->formatted_total)],
            ['Collateral', $this->sanitize($post->collateral_description)],
            ['Repayment Period', $post->formatted_repayment],
            ['Status', $this->sanitize(ucfirst((string) $post->status))],
            ['Posted Date', $this->sanitize($post->created_at?->format('F j, Y \a\t H:i'))],
        ];

        if ($post->closed_at) {
            $details[] = ['Closed Date', $this->sanitize($post->closed_at->format('F j, Y \a\t H:i'))];
        }

        foreach ($details as [$label, $value]) {
            $pdf->SetFont('Helvetica', 'B', 10);
            $pdf->Cell(50, 7, $this->sanitize($label), 0, 0);
            $pdf->SetFont('Helvetica', '', 10);
            $pdf->Cell(0, 7, ': ' . $value, 0, 1);
        }

        $pdf->Ln(5);

        // Description (decode HTML entities and strip HTML tags from Trix content)
        $pdf->SetFont('Helvetica', 'B', 11);
        $pdf->Cell(0, 8, $this->sanitize('Description'), 0, 1);
        $pdf->SetFont('Helvetica', '', 10);
        $decodedDescription = html_entity_decode((string) $post->description, ENT_QUOTES | ENT_HTML5, 'UTF-8');
        $cleanDescription = strip_tags($decodedDescription);
        $pdf->MultiCell(0, 6, $this->sanitize($cleanDescription));

        $pdf->Ln(10);

        // Footer
        $pdf->Line(20, $pdf->GetY(), 190, $pdf->GetY());
        $pdf->Ln(5);
        $pdf->SetFont('Helvetica', 'I', 8);
        $pdf->SetTextColor(113, 113, 122);
        $pdf->Cell(0, 5, $this->sanitize('This document is generated by Kamibantu. It is not a legally binding contract.'), 0, 1, 'C');
        $pdf->Cell(0, 5, $this->sanitize('Generated on ' . now()->format('F j, Y \a\t H:i:s')), 0, 1, 'C');
        $pdf->Cell(0, 5, $this->sanitize('Post ID: #' . $post->id), 0, 1, 'C');

        return response($pdf->Output('S'), 200, [
            'Content-Type' => 'application/pdf',
            'Content-Disposition' => 'attachment; filename="Kamibantu-receipt-' . $post->id . '.pdf"',
        ]);
    }

    private function sanitize(?string $text): string
    {
        if ($text === null || $text === '') {
            return '';
        }

        // Normalize to valid UTF-8 first
        $utf8 = @mb_convert_encoding($text, 'UTF-8', 'UTF-8');
        if (!is_string($utf8)) {
            $utf8 = $text;
        }

        // Convert to ISO-8859-1 for FPDF without using //TRANSLIT
        $converted = @iconv('UTF-8', 'ISO-8859-1//IGNORE', $utf8);
        if (is_string($converted)) {
            return $converted;
        }

        // Fallback to printable ASCII + tabs/newlines if iconv fails on the runtime
        return preg_replace('/[^\x20-\x7E\r\n\t]/', '', $utf8) ?? '';
    }
}